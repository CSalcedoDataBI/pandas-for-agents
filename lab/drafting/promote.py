"""Promote passing drafts from lab/drafting/out/ to skills/pandas-reference/traps/.

    python lab/drafting/promote.py

Copies only drafts whose last attempt passed every check in draft.py and whose last independent
review (review.py) found nothing, and writes the index table
of skills/pandas-reference/traps/README.md from them. The promotion itself goes through a PR, where
check_names.py runs again on skills/.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
TRAPS = ROOT / "skills" / "pandas-reference" / "traps"


def main() -> int:
    TRAPS.mkdir(parents=True, exist_ok=True)
    rows = []
    for result_file in sorted((HERE / "out").glob("*.json")):
        if result_file.name.endswith(".review.json"):
            continue
        result = json.loads(result_file.read_text(encoding="utf-8"))
        if not result["passed"]:
            print(f"skip {result['batch']}: did not pass")
            continue
        review_file = result_file.with_name(f"{result['batch']}.review.json")
        review = json.loads(review_file.read_text(encoding="utf-8")) if review_file.exists() else None
        if not review or review["review"]["verdict"] != "ok":
            print(f"skip {result['batch']}: its last review (review.py) is not clean")
            continue
        shutil.copyfile(result_file.with_suffix(".md"), TRAPS / f"{result['batch']}.md")
        traps = len(result["attempts"][-1]["card"]["traps"])
        rows.append(f"| [{result['title']}]({result['batch']}.md) | {traps} |")
        print(f"promoted {result['batch']}")
    index = ["# Trap cards", "", "One card per group of the catalogue. Generated by "
             "`lab/drafting/promote.py`; do not edit by hand.", "", "| Card | Traps |", "|---|---|", *rows, ""]
    (TRAPS / "README.md").write_text("\n".join(index), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
